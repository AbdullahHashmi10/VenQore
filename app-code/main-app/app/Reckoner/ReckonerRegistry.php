    /**
     * Builds one registry entry with sensible defaults, so ~20 new Phase 2
     * entries don't each repeat every field verbatim. Every field from §3.1
     * is still present in the resulting array — this only removes
     * boilerplate, not the contract.
     */
    private static function scalar(
        string $key,
        string $domain,
        string $label,
        string $description,
        string $help,
        string $unit,
        string $direction,
        array $permissions,
        ?string $capability,
        string $source,
        string $method,
        ?array $periods = null,
        ?string $defaultPeriod = null,
        ?string $feature = null,
        string $scope = 'tenant',
        bool $signed = false,
        ?string $drillRoute = null,
    ): array {
        return [
            'key' => $key,
            'domain' => $domain,
            'label' => $label,
            'generic' => $label,
            'description' => $description,
            'help' => $help,
            'shape' => ReckonerShape::SCALAR,
            'unit' => $unit,
            'precision' => $unit === 'currency' ? 2 : 0,
            'direction' => $direction,
            'signed' => $signed,
            'periods' => $periods ?? ReckonerPeriod::KEYS,
            'default_period' => $defaultPeriod ?? 'today',
            'supports_comparison' => ($periods ?? null) !== ['live'],
            'supports_series' => ($periods ?? null) !== ['live'],
            'series_granularity' => ($periods ?? null) === ['live'] ? [] : ['daily', 'weekly', 'monthly', 'quarterly', 'yearly'],
