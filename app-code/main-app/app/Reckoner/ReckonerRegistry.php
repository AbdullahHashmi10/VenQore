 * Phase 2 adds every metric the nine newly-built sources support — inventory
 * counts, party/purchasing/production/staff/operations/tax figures, and the
 * platform-scoped MRR/tenant-count pair. This is short of the spec's ~250-key
 * full catalogue (that volume assumes ~60 ReportController methods fully
 * read and ported one-by-one, which this session's budget did not allow),
 * but every metric that exists here is wired to a real, schema-verified
 * source — nothing is a stub returning an invented number, with the one
 * explicitly flagged exception documented on PlatformSource::mrr().
